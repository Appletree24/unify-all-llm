test('trial compares the same dirty tree and executor, tests and diffs both results, then applies only the selected patch', async t => {
  const cwd = workspace(t);
  const git = (...args) => execFileSync('git', args, { cwd, encoding: 'utf8' });
  git('init', '-q');
  git('config', 'core.autocrlf', 'false');
  writeFileSync(join(cwd, 'count.txt'), 'base\n');
  writeFileSync(join(cwd, 'check.cjs'), "const fs = require('node:fs'); process.exit(fs.readFileSync('count.txt', 'utf8') === 'good\\n' ? 0 : 1);");
  git('add', '.');
  git('-c', 'user.name=Test', '-c', 'user.email=test@localhost', 'commit', '-qm', 'base');
  writeFileSync(join(cwd, 'count.txt'), 'work in progress\n');
  writeFileSync(join(cwd, 'new.txt'), 'user file\n');
  const originalIndex = git('write-tree');
  const source = await planRun(cwd, [reply('a', 'GOOD_PLAN'), reply('b', 'BAD_PLAN')]);
  const worker = target('worker', async function* (req) {
    assert.notEqual(req.cwd, cwd);
    assert.equal(readFileSync(join(req.cwd, 'count.txt'), 'utf8'), 'work in progress\n');
    assert.equal(readFileSync(join(req.cwd, 'new.txt'), 'utf8'), 'user file\n');
    assert.ok(!readdirSync(req.cwd).includes('.unify'));
    writeFileSync(join(req.cwd, 'count.txt'), req.prompt.includes('GOOD_PLAN') ? 'good\n' : 'bad\n');
    yield { type: 'done', text: 'done' };
  }, { askPolicy: 'read-tools', exec: true });
  const trial = await runTrial(cwd, source, ['a','b'], worker, 'node check.cjs', 8000, signal());
  assert.deepEqual(trial.variants.map(r => r.state), ['passed', 'failed'], JSON.stringify(trial));
  assert.deepEqual(trial.variants[0].files, ['count.txt']);
  assert.match(trialDiff(cwd, trial.id, 2), /\+bad/);
  assert.equal(readFileSync(join(cwd, 'count.txt'), 'utf8'), 'work in progress\n');
  assert.equal(git('worktree', 'list', '--porcelain').match(/^worktree /gm).length, 1);
  const runCli = args => execFileSync(process.execPath, [cli, ...args], { cwd, encoding: 'utf8' });
  assert.match(runCli(['trial','show',trial.id]), /验证失败/);
  assert.match(runCli(['trial','diff',trial.id,'1']), /\+good/);
  const ui = new App({ cols: () => 110, rows: () => 24, write() {} }, cwd, { providers: ['a'] }, [reply('a','ok')]);
  t.after(() => ui.dispose());
  await ui.init();
  submit(ui, '/trial show ' + trial.id);
  ui.invalidate();
  assert.match(ui.snapshot().join('\n'), /验证通过.*验证失败/);
  ui.handleKey({ name: 'char', text: 'd' });
  ui.invalidate();
  assert.match(ui.snapshot().join('\n'), /\+good.*\+bad/);
  ui.handleKey({ name: 'esc' });
  writeFileSync(join(cwd, 'count.txt'), 'conflicting change\n');
  assert.throws(() => applyTrial(cwd, trial.id, 1), /apply|patch/i);
  assert.equal(readFileSync(join(cwd, 'count.txt'), 'utf8'), 'conflicting change\n');
  writeFileSync(join(cwd, 'count.txt'), 'work in progress\n');
  runCli(['trial','apply',trial.id,'1','--yes']);
  assert.equal(readFileSync(join(cwd, 'count.txt'), 'utf8'), 'good\n');
  assert.equal(git('write-tree'), originalIndex);
  assert.throws(() => applyTrial(cwd, trial.id, 2), /已采纳/);
});

test('TUI handoff creates an editable draft and carries only its reviewed text into a distinct session', async t => {
  const cwd = workspace(t);
  const writer = target('writer', async function* (req) {
    yield { type: 'done', text: req.prompt.includes('交接草稿') ? 'draft summary' : 'reply to question' };
  });
  const app = new App({ cols: () => 120, rows: () => 30, write() {} }, cwd, { providers: ['writer'] }, [writer]);
  t.after(() => app.dispose());
  await app.init();
  submit(app, 'private earlier discussion');
  await app.waitForIdle();
  const source = loadRun(cwd);
  submit(app, '/handoff');
  await app.waitForIdle();
  app.invalidate();
  assert.match(app.snapshot().join('\n'), /编辑交接单/);
  const dir = join(cwd, '.unify', 'handoffs');
  const name = readdirSync(dir)[0], id = name.slice(0,-3);
  assert.match(readHandoff(cwd, id).answer, /draft summary/);
  app.handleKey({ name: 'down' });
  app.handleKey({ name: 'enter' });
  app.handleKey({ name: 'paste', text: ' EDITED' });
  app.handleKey({ name: 'enter' });
  assert.match(readHandoff(cwd, id).answer, /EDITED/);
  app.handleKey({ name: 'esc' });
  submit(app, '/handoff use ' + id);
  submit(app, 'next task');
  await app.waitForIdle();
  const next = loadRun(cwd);
  assert.notEqual(next.sessionId, source.sessionId);
  assert.equal(next.input.history.length, 1);
  assert.match(next.calls.find(c => c.scope === 'answer').input.prompt, /EDITED/);
  assert.doesNotMatch(next.input.prompt, /private earlier discussion/);
  assert.throws(() => readHandoff(cwd, '../bad'));
});

test('recommendations use saved results by case version and exact model setup, include quota and work without data', async t => {
  const cwd = workspace(t);
  const targets = [reply('a','yes'), reply('b','wrong')];
  const available = new Map(targets.map(t => [t.id, true]));
  const current = () => rankTargets(cwd, targets, available, []);
  assert.equal(current().recommended, null);
  const c = { version: 1, task: { title: 'exact', prompt: 'say yes', files: [] },
    review: { skill: 'test', negative: 'no', positive: 'yes', grader: { kind: 'exact', expected: 'yes' } } };
  const id = storeValidated(cwd, c);
  const coll = saveCollection(cwd, 'specific', [id]);
  const models = targets.map(target => ({ target, timeoutMs: 8000 }));
  const rows = await runBench(cwd, [id], models);
  assert.deepEqual(rows.map(r => r.status), ['pass','fail']);
  recordBenchResults(cwd, rows, targets);
  const ranked = rankTargets(cwd, targets, available, [], coll.id);
  assert.equal(ranked.recommended, 'a');
  assert.equal(ranked.rows[0].samples, 1);
  assert.equal(ranked.rows[0].passed, 1);
  assert.equal(rankTargets(cwd, [{ ...targets[0], model: 'other' }], available, []).recommended, null);
  assert.equal(rankTargets(cwd, targets, available, [{ targetId: 'a', provider: 'a', reading: { status: 'ok',
    limits: [{ label: 'limit', remaining: 0, unit: '%' }] } }]).recommended, null);
  const app = new App({ cols: () => 100, rows: () => 24, write() {} }, cwd, { providers: ['b'] }, targets);
  t.after(() => app.dispose());
  await app.init();
  submit(app, '/recommend ' + coll.id);
  await app.waitForIdle();
  app.invalidate();
  assert.match(app.snapshot().join('\n'), /推荐 a/);
  app.handleKey({ name: 'enter' });
  submit(app, 'use the recommended model');
  await app.waitForIdle();
  assert.deepEqual(loadRun(cwd).targets.map(t => t.id), ['a']);
});
